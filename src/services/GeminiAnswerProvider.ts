/**
 * Live Google Gemini 1.5 Flash Answer Provider
 * Connects the AI Learning Assistant directly to Google Gemini API for real-time technical answers.
 */

import type {
  IAnswerProvider,
  AssistantRequest,
  AssistantResponse,
  ExplanationStyle,
} from '@/types/assistant';

export class GeminiAnswerProvider implements IAnswerProvider {
  readonly providerType = 'gemini' as const;
  private apiKey: string;
  private model: string;

  constructor(apiKey: string, model = 'gemini-1.5-flash') {
    this.apiKey = apiKey.trim();
    this.model = model;
  }

  setApiKey(apiKey: string) {
    this.apiKey = apiKey.trim();
  }

  async getAnswer(request: AssistantRequest): Promise<AssistantResponse> {
    if (!this.apiKey) {
      return {
        isSupported: false,
        selectedStyle: request.selectedStyle || 'simple',
        content:
          'Please configure a valid Google Gemini API key to receive live AI answers. You can get a free key from Google AI Studio (https://aistudio.google.com).',
        suggestedQuestions: this.getSuggestedQuestions(),
        fallbackMessage: 'Missing Gemini API Key',
        providerType: 'mock',
        confidenceScore: 0,
      };
    }

    const style = request.selectedStyle || 'simple';
    const systemPrompt = `You are a Senior Salesforce Technical Lead and AI Learning Assistant for the "IT Daily Upskilling" application.
Answer the following technical question accurately, concisely, and with enterprise-grade quality.
Target Explanation Style: "${style.toUpperCase()}"
- If SIMPLE: Explain using clear everyday analogies and straightforward concepts.
- If REAL_WORLD: Provide a realistic enterprise business requirement (e.g. Banking, Healthcare, or Insurance), feature used, implementation approach, and expected outcome.
- If INTERVIEW: Provide the exact structured technical answer expected in a senior technical interview, including governor limits, interfaces, and architecture considerations.

Include official documentation references or citations where applicable.`;

    let activeModels: string[] = [];
    try {
      const listRes = await fetch(`https://generativelanguage.googleapis.com/v1beta/models?key=${this.apiKey}`);
      if (listRes.ok) {
        const listData = await listRes.json();
        const models: any[] = listData.models || [];
        activeModels = models
          .filter((m) => m.supportedGenerationMethods?.includes('generateContent'))
          .map((m) => m.name);
      }
    } catch {
      // fallback
    }

    if (activeModels.length === 0) {
      activeModels = [
        'models/gemini-2.0-flash',
        'models/gemini-1.5-flash',
        'models/gemini-1.5-flash-latest',
        'models/gemini-1.5-pro',
      ];
    }

    let data: any = null;
    let lastError = '';

    try {
      for (const modelPath of activeModels) {
        const endpoint = `https://generativelanguage.googleapis.com/v1beta/${modelPath}:generateContent?key=${this.apiKey}`;
        try {
          const response = await fetch(endpoint, {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({
              contents: [
                {
                  parts: [
                    {
                      text: `${systemPrompt}\n\nUser Question: ${request.question}${
                        request.topicId ? `\nContext Topic: ${request.topicId}` : ''
                      }`,
                    },
                  ],
                },
              ],
              generationConfig: {
                temperature: 0.2,
                maxOutputTokens: 1024,
              },
            }),
          });

          if (response.ok) {
            data = await response.json();
            this.model = modelPath.replace('models/', '');
            break;
          } else {
            const errorData = await response.json().catch(() => ({}));
            lastError = errorData?.error?.message || response.statusText;
          }
        } catch (e: any) {
          lastError = e.message;
        }
        if (data) break;
      }

      if (!data) {
        throw new Error(`Gemini API Error: ${lastError || 'No supported Gemini model available'}`);
      }

      const generatedText =
        data.candidates?.[0]?.content?.parts?.[0]?.text ||
        'No response generated by Gemini. Please try again.';

      return {
        isSupported: true,
        selectedStyle: style,
        content: generatedText,
        suggestedQuestions: this.getSuggestedQuestions({ topicId: request.topicId }),
        providerType: 'mock', // Interface compatibility
        confidenceScore: 0.95,
        matchedAnswer: {
          knowledgeId: `gemini-${Date.now()}`,
          topicId: request.topicId || 'general_salesforce',
          topicTitle: request.topicId ? request.topicId.replace(/_/g, ' ') : 'Salesforce Architecture',
          canonicalQuestion: request.question,
          simpleExplanation: generatedText.substring(0, 300),
          realWorldScenario: {
            domain: 'Sales Automation',
            title: 'Live AI Generated Architecture',
            businessRequirement: 'Generated live via Google Gemini 1.5 Flash',
            featureUsed: 'Gemini 1.5 Flash Model',
            implementationApproach: 'Direct client-side query evaluation',
            expectedResult: 'Instantaneous technical resolution',
          },
          interviewAnswer: generatedText.substring(0, 400),
          relatedLessonIds: request.lessonId ? [request.lessonId] : [],
          sourceReference: {
            sourceName: 'Google Gemini 1.5 Flash (Live Technical Assistant)',
            sourceUrl: 'https://developer.salesforce.com/docs',
            evidenceStatus: 'verified',
          },
          version: 'Live AI',
        },
      };
    } catch (err: any) {
      return {
        isSupported: false,
        selectedStyle: style,
        content: `Error connecting to Gemini API: ${err.message}. Please check your API key and network connection.`,
        suggestedQuestions: this.getSuggestedQuestions(),
        fallbackMessage: err.message,
        providerType: 'mock',
        confidenceScore: 0,
      };
    }
  }

  getSuggestedQuestions(context?: { topicId?: string; lessonId?: string }): string[] {
    return [
      'How do I avoid governor limits in batch and queueable Apex?',
      'What are the key architectural differences between Flow and Apex Trigger?',
      'When should I use Lightning Message Service vs Component Events in LWC?',
      'How does Salesforce handle Mixed DML operations in test classes?',
    ];
  }
}
