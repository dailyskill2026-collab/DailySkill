/**
 * Live OpenAI Answer Provider (gpt-4o-mini / gpt-4o)
 * Connects the AI Learning Assistant directly to OpenAI Chat Completions API.
 */

import type {
  IAnswerProvider,
  AssistantRequest,
  AssistantResponse,
} from '@/types/assistant';

export class OpenAIAnswerProvider implements IAnswerProvider {
  readonly providerType = 'openai' as const;
  private apiKey: string;
  private model: string;

  constructor(apiKey: string, model = 'gpt-4o-mini') {
    this.apiKey = apiKey.trim();
    this.model = model;
  }

  setApiKey(apiKey: string) {
    this.apiKey = apiKey.trim();
  }

  async getAnswer(request: AssistantRequest): Promise<AssistantResponse> {
    if (!this.apiKey) {
      return {
        isSupported: false,
        selectedStyle: request.selectedStyle || 'simple',
        content: 'Please configure a valid OpenAI API key in settings to receive live answers.',
        suggestedQuestions: this.getSuggestedQuestions(),
        fallbackMessage: 'Missing OpenAI API Key',
        providerType: 'mock',
        confidenceScore: 0,
      };
    }

    const style = request.selectedStyle || 'simple';
    const systemPrompt = `You are a Senior Salesforce Technical Lead and AI Learning Assistant for the "IT Daily Upskilling" application.
Answer the following technical question accurately, concisely, and with enterprise-grade quality.
Target Explanation Style: "${style.toUpperCase()}"
- If SIMPLE: Explain using clear everyday analogies and straightforward concepts.
- If REAL_WORLD: Provide a realistic enterprise business requirement (e.g. Banking, Healthcare, or Insurance), feature used, implementation approach, and expected outcome.
- If INTERVIEW: Provide the exact structured technical answer expected in a senior technical interview, including governor limits, interfaces, and architecture considerations.

Include official documentation references or citations where applicable.`;

    try {
      const response = await fetch('https://api.openai.com/v1/chat/completions', {
        method: 'POST',
        headers: {
          Authorization: `Bearer ${this.apiKey}`,
          'Content-Type': 'application/json',
        },
        body: JSON.stringify({
          model: this.model,
          messages: [
            { role: 'system', content: systemPrompt },
            {
              role: 'user',
              content: `Question: ${request.question}${
                request.topicId ? `\nContext Topic: ${request.topicId}` : ''
              }`,
            },
          ],
          temperature: 0.2,
          max_tokens: 1024,
        }),
      });

      if (!response.ok) {
        const errorData = await response.json().catch(() => ({}));
        const msg = errorData?.error?.message || response.statusText;
        throw new Error(`OpenAI API Error: ${msg}`);
      }

      const data = await response.json();
      const generatedText =
        data.choices?.[0]?.message?.content ||
        'No response generated by OpenAI. Please try again.';

      return {
        isSupported: true,
        selectedStyle: style,
        content: generatedText,
        suggestedQuestions: this.getSuggestedQuestions({ topicId: request.topicId }),
        providerType: 'mock',
        confidenceScore: 0.95,
        matchedAnswer: {
          knowledgeId: `openai-${Date.now()}`,
          topicId: request.topicId || 'general_salesforce',
          topicTitle: request.topicId ? request.topicId.replace(/_/g, ' ') : 'Salesforce Architecture',
          canonicalQuestion: request.question,
          simpleExplanation: generatedText.substring(0, 300),
          realWorldScenario: {
            domain: 'Sales Automation',
            title: 'Live OpenAI Generated Architecture',
            businessRequirement: 'Generated live via OpenAI gpt-4o-mini',
            featureUsed: this.model,
            implementationApproach: 'Direct API query evaluation',
            expectedResult: 'Instantaneous technical resolution',
          },
          interviewAnswer: generatedText.substring(0, 400),
          relatedLessonIds: request.lessonId ? [request.lessonId] : [],
          sourceReference: {
            sourceName: 'OpenAI (Live Technical Assistant)',
            sourceUrl: 'https://developer.salesforce.com/docs',
            evidenceStatus: 'verified',
          },
          version: 'Live AI',
        },
      };
    } catch (err: any) {
      return {
        isSupported: false,
        selectedStyle: style,
        content: `Error connecting to OpenAI API: ${err.message}. Please check your API key.`,
        suggestedQuestions: this.getSuggestedQuestions(),
        fallbackMessage: err.message,
        providerType: 'mock',
        confidenceScore: 0,
      };
    }
  }

  getSuggestedQuestions(context?: { topicId?: string; lessonId?: string }): string[] {
    return [
      'How do I avoid governor limits in batch and queueable Apex?',
      'What are the key architectural differences between Flow and Apex Trigger?',
      'When should I use Lightning Message Service vs Component Events in LWC?',
      'How does Salesforce handle Mixed DML operations in test classes?',
    ];
  }
}
